// Package mock provides a mock LLM client for testing.
package mock

import (
	"context"
	"fmt"
	"io"
	"time"

	"github.com/jo-hoe/gostwriter/internal/config"
	"github.com/jo-hoe/gostwriter/internal/llm"
)

var _ llm.Client = (*Client)(nil)
var _ llm.FilenameAdvisor = (*Client)(nil)

// mockConversation is the mock implementation of llm.Conversation. It carries
// no state because the mock does not continue real exchanges.
type mockConversation struct{}

func (mockConversation) Provider() string { return "mock" }

// Client is a mock LLM client that returns canned Markdown after a configurable delay.
type Client struct {
	delay  time.Duration
	prefix string
}

// New creates a mock LLM client from configuration.
func New(cfg config.MockSettings) *Client {
	return &Client{
		delay:  cfg.Delay,
		prefix: cfg.Prefix,
	}
}

// TranscribeImage satisfies llm.Client. It returns canned Markdown after a configurable delay.
func (c *Client) TranscribeImage(ctx context.Context, r io.Reader, mime string) (string, llm.Conversation, error) {
	// Consume a little to simulate reading (optional)
	buf := make([]byte, 256)
	_, _ = r.Read(buf)

	// Simulate processing delay
	if c.delay > 0 {
		t := time.NewTimer(c.delay)
		defer t.Stop()
		select {
		case <-ctx.Done():
			return "", nil, fmt.Errorf("mock: %w", ctx.Err())
		case <-t.C:
		}
	}

	md := fmt.Sprintf("%s\n\nThis is a mock transcription for an image of type %q.\n\n- This output is generated by the mock LLM client.\n- Replace with a real LLM implementation later.\n", c.prefix, mime)
	return md, mockConversation{}, nil
}

// SuggestFilename satisfies llm.FilenameAdvisor. It returns a static slug after
// the configured delay; the mock does not inspect the conversation.
func (c *Client) SuggestFilename(ctx context.Context, _ llm.Conversation) (string, error) {
	if c.delay > 0 {
		t := time.NewTimer(c.delay)
		defer t.Stop()
		select {
		case <-ctx.Done():
			return "", fmt.Errorf("mock: %w", ctx.Err())
		case <-t.C:
		}
	}
	return "mock-document", nil
}
